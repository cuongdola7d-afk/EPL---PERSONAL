-- Read-only source/target inventory. Run before any dump/import; do not print row contents.
SET time_zone = '+00:00';
SELECT VERSION() AS mysql_version,DATABASE() AS database_name,@@server_uuid AS server_uuid,
       @@lower_case_table_names AS lower_case_table_names,@@session.time_zone AS session_timezone;
SHOW SESSION STATUS LIKE 'Ssl_cipher';

SELECT TABLE_TYPE,COUNT(*) AS object_count,COALESCE(SUM(DATA_LENGTH+INDEX_LENGTH),0) AS estimated_bytes
FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() GROUP BY TABLE_TYPE;
SELECT TABLE_NAME,ENGINE,TABLE_COLLATION,AUTO_INCREMENT
FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME;
SELECT 'routines' AS object_type,COUNT(*) AS object_count FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA=DATABASE()
UNION ALL SELECT 'triggers',COUNT(*) FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE()
UNION ALL SELECT 'events',COUNT(*) FROM information_schema.EVENTS WHERE EVENT_SCHEMA=DATABASE();

SELECT TABLE_NAME,COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,CHARACTER_SET_NAME,COLLATION_NAME,EXTRA
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,ORDINAL_POSITION;
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE
FROM information_schema.TABLE_CONSTRAINTS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT TABLE_NAME,INDEX_NAME,NON_UNIQUE,SEQ_IN_INDEX,COLUMN_NAME
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX;
